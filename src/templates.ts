export const contractModule = (c: {
  module: string;
  ops: Op[];
  info: string[];
  paths: string[];
  components: string[];
  items: string[];
  body: string[];
}) => `
pub mod ${c.module} {
    use super::*;

    /// An operation of this contract, carrying what the contract states of it (\`Route\`). The values are written once, on the
    /// constants below (\`Operation::${c.ops[0] ? operationConst(c.ops[0]) : "NONE"}\`, ...).
    #[derive(Debug, Clone, PartialEq, Eq)]
    pub enum Operation {
${lines(c.ops.map((o) => `        ${o.trait}(Route),`))}
    }

    impl Operation {
${lines(c.ops.map((o) => `        pub const ${operationConst(o)}: Operation = Operation::${o.trait}(Route {
            method: Method::${o.method.toUpperCase()},
            path: ${q(o.path)},
            extensions: &[${o.extensions.map((e) => `Extension { name: ${q(e.name)}, json: ${q(JSON.stringify(e.json))} }`).join(", ")}],
        });`))}

        pub const ALL: [Operation; ${c.ops.length}] = [
${lines(c.ops.map((o) => `            Self::${operationConst(o)},`))}
        ];

    }

    impl AsRef<Route> for Operation {
        fn as_ref(&self) -> &Route {
            match self {
                ${c.ops.map((o) => `Self::${o.trait}(route)`).join("\n                | ")} => route,
            }
        }
    }

${lines(c.body)}
${router(c.ops)}

    #[derive(utoipa::OpenApi)]
    #[openapi(
        info(${c.info.join(", ")}),
        paths(${c.paths.join(", ")}),
        components(schemas(${c.components.join(", ")})),
    )]
    pub struct ApiDoc;

    /// The OpenAPI document of this contract, as the TypeSpec emitter writes it.
    pub fn document() -> serde_json::Value {
        let mut document = serde_json::to_value(<ApiDoc as utoipa::OpenApi>::openapi()).expect("the document serializes");
        finish(&mut document, &[${c.items.join(", ")}]);
        document
    }
}`;
